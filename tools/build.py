#!/usr/bin/env python3
"""Build step for the NGHTMRE site.

    python3 tools/build.py                 # rewrite js/data.js only
    python3 tools/build.py --tex           # also redraw the torn edges, paint, paper
    python3 tools/build.py --src <folder>  # also remake img/ from the originals

Needs Pillow and numpy for --tex and --src. The originals (the pictures taken
from nghtmre.com, YouTube and nghtmreshop.com) are not kept in this repo.
"""
import argparse, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)

SEATED = "https://cdn.seated.com/api/tour/b3f93a40-bbae-46a6-9c9c-24f747b4b48c?include=tour-events"


# ---------------------------------------------------------------- data.js

def tour_snapshot(refresh):
    path = P("data/tour.json")
    if refresh or not os.path.exists(path):
        raw = subprocess.run(["curl", "-sfL", "-H", "Accept: application/vnd.api+json", SEATED],
                             check=True, capture_output=True).stdout
        ev = []
        for e in json.loads(raw).get("included", []):
            if e.get("type") != "tour-events":
                continue
            a = e["attributes"]
            ev.append({
                "id": e["id"],
                "start": a["starts-at-date-local"],
                "end": a.get("ends-at-date-local") or a["starts-at-date-local"],
                "venue": (a.get("venue-name") or "").strip(),
                "place": (a.get("formatted-address") or "").strip(),
                "note": (a.get("details") or "").strip(),
                "soldOut": bool(a.get("is-sold-out")),
            })
        ev.sort(key=lambda x: x["start"])
        json.dump(ev, open(path, "w"), indent=1, ensure_ascii=False)
    return json.load(open(path))


def write_data(refresh_tour):
    data = {
        "tour": tour_snapshot(refresh_tour),
        "album": json.load(open(P("data/album.json"))),
        "catalog": json.load(open(P("data/catalog.json"))),
        "videos": json.load(open(P("data/videos.json"))),
        "merch": json.load(open(P("data/merch.json"))),
    }
    with open(P("js/data.js"), "w") as f:
        f.write("// Generated by tools/build.py from data/*.json. Do not edit by hand.\n")
        f.write("window.NGHT = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("js/data.js:", len(data["tour"]), "shows,", len(data["catalog"]), "records,",
          len(data["videos"]), "videos,", len(data["merch"]), "merch")


# ---------------------------------------------------------------- textures

def textures():
    import numpy as np
    from PIL import Image, ImageFilter

    os.makedirs(P("tex"), exist_ok=True)

    def vnoise(n, cells, rng, smooth=True):
        """Periodic 1-D value noise: n samples over `cells` lattice cells."""
        v = rng.random(cells)
        x = np.arange(n) * cells / n
        i = np.floor(x).astype(int)
        t = x - i
        if smooth:
            t = t * t * (3 - 2 * t)
        return v[i % cells] * (1 - t) + v[(i + 1) % cells] * t

    def tear_line(n, rng, depth):
        """A torn edge: big lazy wander, angular bites, fine fibre jitter. 0..depth."""
        y = 0.50 * vnoise(n, 5, rng) + 0.26 * vnoise(n, 17, rng, False)
        y += 0.14 * vnoise(n, 61, rng, False) + 0.07 * vnoise(n, 190, rng, False)
        y += 0.03 * rng.random(n)
        y = (y - y.min()) / (y.max() - y.min())
        return y * depth

    def save_mask(alpha, name):
        """alpha: float 0..1, 2x oversampled -> white PNG with that alpha."""
        a = Image.fromarray((np.clip(alpha, 0, 1) * 255).astype("uint8"), "L")
        a = a.resize((a.width // 2, a.height // 2), Image.LANCZOS)
        im = Image.merge("LA", (Image.new("L", a.size, 255), a))
        im.save(P("tex", name), optimize=True)

    def edge_pair(name, seed, length=1600, depth=84, vertical=False):
        rng = np.random.default_rng(seed)
        n, d = length * 2, depth * 2
        line = tear_line(n, rng, d * 0.62) + d * 0.30          # the sheet's edge
        fibre = line - (4 + 22 * vnoise(n, 40, rng) ** 2 + 5 * rng.random(n)) * 2 * 0.5
        yy = np.arange(d)[:, None]
        solid = np.clip(yy - line[None, :], 0, 1)
        fib = np.clip(yy - fibre[None, :], 0, 1)
        if vertical:                                           # opaque to the right
            solid, fib = solid.T, fib.T
        save_mask(solid, f"{name}.png")
        save_mask(fib, f"{name}-f.png")

    edge_pair("tear-a", 11)
    edge_pair("tear-b", 23)
    edge_pair("tear-c", 37)
    edge_pair("vtear-a", 51, vertical=True)

    def frame_pair(name, w, h, seed, inset=0.035):
        """A sheet torn on all four sides."""
        rng = np.random.default_rng(seed)
        W, H = w * 2, h * 2
        m = int(min(W, H) * inset)
        out = []
        for extra in (0, 1):
            a = np.ones((H, W))
            for side in range(4):
                n = W if side < 2 else H
                line = tear_line(n, rng, m * 1.5) + m * 0.2
                if extra:
                    line = np.clip(line - m * (0.25 + 0.5 * vnoise(n, 30, rng) ** 2), 0, None)
                if side < 2:
                    d = np.arange(H)[:, None] if side == 0 else (H - 1 - np.arange(H))[:, None]
                    a *= np.clip(d - line[None, :], 0, 1)
                else:
                    d = np.arange(W)[None, :] if side == 2 else (W - 1 - np.arange(W))[None, :]
                    a *= np.clip(d - line[:, None], 0, 1)
            out.append(a)
        save_mask(out[0], f"{name}.png")
        save_mask(out[1], f"{name}-f.png")

    frame_pair("frame-sq", 700, 700, 71)
    frame_pair("frame-wide", 1280, 720, 83, inset=0.03)
    frame_pair("frame-strip", 1400, 260, 97, inset=0.09)

    def fft_noise(n, rng, sx, sy, angle=0.0):
        """Periodic noise, smeared sx along `angle` and sy across it."""
        f = np.fft.fft2(rng.standard_normal((n, n)))
        ky = np.fft.fftfreq(n)[:, None]
        kx = np.fft.fftfreq(n)[None, :]
        c, s = np.cos(angle), np.sin(angle)
        u, v = kx * c + ky * s, -kx * s + ky * c
        g = np.exp(-2 * np.pi ** 2 * ((u * sx) ** 2 + (v * sy) ** 2))
        out = np.real(np.fft.ifft2(f * g))
        return (out - out.mean()) / (out.std() + 1e-9)

    # --- thick yellow paint -------------------------------------------------
    rng = np.random.default_rng(5)
    n = 1200
    # broad knife strokes in a few directions, each with its own bristle drag
    h = np.zeros((n, n))
    for amp, length, width, ang in ((1.0, 190, 30, 0.10), (0.85, 150, 24, -0.55),
                                    (0.75, 130, 26, 1.25), (0.6, 110, 18, 0.75)):
        stroke = fft_noise(n, rng, length, width, ang)
        drag = fft_noise(n, rng, length * 0.9, 2.2, ang)
        h += amp * (stroke + 0.22 * drag * (0.6 + 0.4 * np.tanh(stroke)))
    h += 0.5 * np.abs(fft_noise(n, rng, 70, 12, -0.2))      # ridges where strokes overlap
    h += 0.10 * fft_noise(n, rng, 3, 3)
    h = np.tanh(h * 0.55)
    gy, gx = np.gradient(h)
    gx = np.roll(h, -1, 1) - np.roll(h, 1, 1)
    gy = np.roll(h, -1, 0) - np.roll(h, 1, 0)
    shade = np.clip(-(gx * 0.55 + gy * 0.85) * 9.0, -1, 1)
    spec = np.clip(shade - 0.45, 0, 1) ** 1.5
    low = fft_noise(n, rng, 70, 70) * 0.5
    base = np.array([252, 192, 0], float)
    deep = np.array([226, 128, 0], float)
    lite = np.array([255, 226, 96], float)
    t = np.clip(0.5 - shade * 0.6 - h * 0.12 + low * 0.10, 0, 1)[..., None]
    col = base * (1 - np.clip(t - 0.5, 0, 1) * 2) + deep * np.clip(t - 0.5, 0, 1) * 2
    col = col * (1 - np.clip(0.5 - t, 0, 1) * 1.2) + lite * np.clip(0.5 - t, 0, 1) * 1.2
    col += spec[..., None] * np.array([40, 40, 70])
    Image.fromarray(np.clip(col, 0, 255).astype("uint8")).save(P("tex/paint.webp"), quality=74, method=6)

    # --- paper ---------------------------------------------------------------
    rng = np.random.default_rng(8)
    n = 900
    p = 0.9 * fft_noise(n, rng, 60, 60) + 0.5 * fft_noise(n, rng, 14, 14)
    for ang in (0.3, 1.2, 2.1, 2.8):
        p += 0.35 * fft_noise(n, rng, 14, 0.8, ang)        # fibres
    p += 0.35 * rng.standard_normal((n, n))
    col = np.array([236, 231, 217], float) + p[..., None] * np.array([3.2, 3.2, 3.6])
    Image.fromarray(np.clip(col, 0, 255).astype("uint8")).save(P("tex/paper.webp"), quality=70, method=6)

    # --- grunge: eaten-away print, used as a mask on big letters -------------
    rng = np.random.default_rng(13)
    n = 640
    g = 0.8 * fft_noise(n, rng, 5, 5) + 0.9 * fft_noise(n, rng, 1.5, 1.5)
    g += 0.7 * fft_noise(n, rng, 26, 0.8, 1.52)          # drags down the sheet
    g += 0.45 * fft_noise(n, rng, 60, 60)
    hole = np.clip((g - 1.75) * 3.0, 0, 1)               # where the ink is gone
    speck = (rng.random((n, n)) > 0.994).astype(float)
    a = 1 - np.clip(hole + speck * 0.8, 0, 1)
    im = Image.fromarray((a * 255).astype("uint8"), "L").filter(ImageFilter.GaussianBlur(0.5))
    Image.merge("LA", (Image.new("L", im.size, 255), im)).save(P("tex/grunge.png"), optimize=True)

    # --- film grain ----------------------------------------------------------
    rng = np.random.default_rng(21)
    n = 220
    v = rng.random((n, n))
    grey = (v > 0.5).astype("uint8") * 255
    alpha = (np.abs(v - 0.5) * 2 * 70).astype("uint8")
    Image.merge("LA", (Image.fromarray(grey, "L"), Image.fromarray(alpha, "L"))).save(P("tex/grain.png"), optimize=True)
    print("tex/: redrawn")


# ---------------------------------------------------------------- pictures

def pictures(src):
    from PIL import Image
    S = lambda n: os.path.join(src, n)
    os.makedirs(P("img"), exist_ok=True)

    def fit(im, w):
        if im.width <= w:
            return im
        return im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)

    # the name, kept as PNG (it is also used as a mask)
    fit(Image.open(S("logo.png")).convert("RGBA"), 1000).save(P("img/logo.png"), optimize=True)
    fit(Image.open(S("favicon.png")).convert("RGBA"), 256).save(P("img/mark.png"), optimize=True)
    fit(Image.open(S("tour_title.png")).convert("RGBA"), 1300).save(P("img/tour-title.webp"), quality=90, method=6)

    hero = Image.open(S("hero.png")).convert("RGB")
    w, h = hero.size
    sq = hero.crop(((w - h) // 2, 0, (w + h) // 2, h))
    sq.resize((1800, 1800), Image.LANCZOS).save(P("img/hero.webp"), quality=76, method=6)
    sq.resize((1000, 1000), Image.LANCZOS).save(P("img/hero-m.webp"), quality=74, method=6)

    foot = Image.open(S("footer.png")).convert("RGB")
    fit(foot, 2000).save(P("img/foil.webp"), quality=74, method=6)
    fw, fh = foot.size
    fit(foot.crop((int(fw * 0.42), 0, fw, fh)), 1000).save(P("img/foil-m.webp"), quality=72, method=6)

    for name, out, w in (("djstage.png", "stage", 1600), ("fog.png", "fog", 1400), ("crowd.png", "crowd", 1800)):
        fit(Image.open(S(name)).convert("RGBA"), w).save(P(f"img/{out}.webp"), quality=78, method=6)

    for v in json.load(open(P("data/videos.json"))):
        im = Image.open(S(f"yt_{v['id']}.jpg")).convert("RGB")
        # YouTube's 4:3 fallbacks carry black bars: cut to 16:9
        if abs(im.width / im.height - 16 / 9) > 0.05:
            nh = round(im.width * 9 / 16)
            top = (im.height - nh) // 2
            im = im.crop((0, top, im.width, top + nh))
        fit(im, 960).save(P(f"img/v-{v['id']}.jpg"), quality=76, optimize=True, progressive=True)

    for i, m in enumerate(json.load(open(P("data/merch.json")))):
        cand = [f for f in os.listdir(src) if f.startswith(f"merch_{i}.")]
        im = Image.open(S(cand[0])).convert("RGBA")
        im.thumbnail((640, 640), Image.LANCZOS)
        im.save(P(f"img/m-{i}.webp"), quality=80, method=6)

    # link preview, 1200 x 630
    card = Image.new("RGB", (1200, 630), (10, 10, 10))
    hh = sq.resize((760, 760), Image.LANCZOS)
    card.paste(hh, (-40, -70))
    paint = Image.open(P("tex/paint.webp")).convert("RGB").resize((700, 700))
    vt = Image.open(P("tex/vtear-a.png")).split()[-1].resize((90, 630))
    card.paste(paint.crop((0, 0, 560, 630)), (640, 0))
    edge = paint.crop((0, 0, 90, 630))
    card.paste(edge, (560, 0), vt)
    title = Image.open(S("tour_title.png")).convert("RGBA")
    title = fit(title, 440)
    black = Image.new("RGBA", title.size, (10, 10, 10, 255))
    card.paste(black, (700, 210), title.split()[-1])
    card.save(P("img/share.jpg"), quality=84, optimize=True)
    print("img/: remade")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", help="folder holding the original pictures")
    ap.add_argument("--tex", action="store_true", help="redraw the textures")
    ap.add_argument("--tour", action="store_true", help="refresh the tour snapshot from Seated")
    a = ap.parse_args()
    if a.tex:
        textures()
    if a.src:
        pictures(a.src)
    write_data(a.tour)
